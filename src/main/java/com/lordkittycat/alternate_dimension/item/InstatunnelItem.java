import java.util.List;

import com.lordkittycat.alternate_dimension.procedures.CreateTunnelProcedure;

public class InstatunnelItem extends Item {
	public InstatunnelItem() {
		super(new Item.Properties());
	}

	@Override
	@OnlyIn(Dist.CLIENT)
	public void appendHoverText(ItemStack itemstack, Item.TooltipContext context, List<Component> list, TooltipFlag flag) {
		super.appendHoverText(itemstack, context, list, flag);
		list.add(Component.translatable("item.alternate_dimension.instatunnel.description_0"));
		list.add(Component.translatable("item.alternate_dimension.instatunnel.description_1"));
	}

	@Override
	public InteractionResult useOn(UseOnContext context) {
		super.useOn(context);
		CreateTunnelProcedure.execute(context.getLevel(), context.getClickedPos().getX(), context.getClickedPos().getY(), context.getClickedPos().getZ(), context.getClickedFace(), context.getItemInHand());
		return InteractionResult.SUCCESS;
	}
}